import { createHash } from 'node:crypto';
import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  renameSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

// Read only public frontend inputs. Never inspect Git state, environment files,
// browser profiles, local league storage, usernames or machine paths for metadata.
export function sourceFingerprint(frontend) {
  const paths = [];
  function collect(folder) {
    if (!existsSync(folder)) return;
    for (const entry of readdirSync(folder, { withFileTypes: true })) {
      if (entry.name.startsWith('.') || entry.name === 'build-info.json') continue;
      const path = join(folder, entry.name);
      if (entry.isDirectory()) collect(path);
      else if (!entry.name.endsWith('.spec.ts')) paths.push(path);
    }
  }
  collect(join(frontend, 'src'));
  collect(join(frontend, 'public'));
  for (const name of [
    'package.json',
    'pnpm-lock.yaml',
    'angular.json',
    'tsconfig.json',
    'tsconfig.app.json',
  ]) {
    const path = join(frontend, name);
    if (existsSync(path)) paths.push(path);
  }
  const theme = resolve(frontend, '../docs/showcase-theme.css');
  if (existsSync(theme)) paths.push(theme);
  const hash = createHash('sha256');
  for (const path of paths.sort())
    hash.update(relative(frontend, path)).update('\0').update(readFileSync(path)).update('\0');
  return hash.digest('hex').slice(0, 10);
}

export function writeBuildInfo(
  frontend,
  { development = false, ifMissing = false, now = new Date() } = {},
) {
  const modulePath = join(frontend, 'generated/build-info.ts');
  const manifestPath = join(frontend, 'public/build-info.json');
  if (ifMissing && existsSync(modulePath) && existsSync(manifestPath)) return;
  const { version } = JSON.parse(readFileSync(join(frontend, 'package.json'), 'utf8'));
  const builtAt = development ? null : now.toISOString();
  const stamp = builtAt
    ?.replaceAll('-', '')
    .replaceAll(':', '')
    .replace(/\.\d{3}Z$/, 'Z');
  const info = {
    version,
    buildId: development ? 'development' : `${stamp}-${sourceFingerprint(frontend)}`,
    builtAt,
  };
  for (const [path, value] of [
    [
      modulePath,
      `// Generated by scripts/write-build-info.mjs. Public build metadata only.\nexport const UI_BUILD_INFO = ${JSON.stringify(info, null, 2)} as const;\n`,
    ],
    [manifestPath, JSON.stringify(info, null, 2) + '\n'],
  ]) {
    mkdirSync(dirname(path), { recursive: true });
    const temporary = path + '.tmp';
    writeFileSync(temporary, value);
    renameSync(temporary, path);
  }
  return info;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const frontend = resolve(dirname(fileURLToPath(import.meta.url)), '..');
  const info = writeBuildInfo(frontend, {
    development: process.argv.includes('--development'),
    ifMissing: process.argv.includes('--if-missing'),
  });
  if (info) process.stdout.write(`UI ${info.version} · ${info.buildId}\n`);
}
